#!/usr/bin/env bash
# Regenerates vendor/holy build files from whatever APKs are in
# vendor/holy/prebuilt. With an argument (the stock product makefile), also
# writes the holy_<BASE_PRODUCT> product that inherits it.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
source "$here/config.env"
v="$here/vendor/holy"

modules=()
{
  echo "// Generated by scripts/gen-vendor.sh. Do not edit."
  for apk in "$v"/prebuilt/*/*.apk; do
    [ -e "$apk" ] || continue
    m="$(basename "$apk" .apk)"; modules+=("$m")
    cat <<BP

android_app_import {
    name: "$m",
    apk: "prebuilt/$m/$m.apk",
    // Re-sign with the build's key so release or debug APKs both install.
    default_dev_cert: true,
    product_specific: true,
    dex_preopt: { enabled: false },
    enforce_uses_libs: false,
}
BP
  done
} > "$v/Android.bp"

{
  echo "# Generated by scripts/gen-vendor.sh. Inherit this from any product to add the Holy apps."
  echo "PRODUCT_PACKAGES += \\"
  for m in "${modules[@]}"; do echo "    $m \\"; done
  echo
  echo "PRODUCT_PRODUCT_PROPERTIES += ro.holy.os=1"
} > "$v/holy.mk"

if [ $# -ge 1 ]; then
  base_mk="$1"
  name="holy_$BASE_PRODUCT"
  cat > "$v/$name.mk" <<MK
# Generated by scripts/gen-vendor.sh: stock $BASE_PRODUCT + the Holy apps.
\$(call inherit-product, $base_mk)
\$(call inherit-product, vendor/holy/holy.mk)
PRODUCT_NAME := $name
PRODUCT_BRAND := Holy
PRODUCT_MODEL := Holy OS ($BASE_PRODUCT)
MK
  cat > "$v/AndroidProducts.mk" <<MK
# Generated by scripts/gen-vendor.sh.
PRODUCT_MAKEFILES := \$(LOCAL_DIR)/$name.mk
COMMON_LUNCH_CHOICES := $name-$RELEASE-$VARIANT
MK
fi
echo "vendor/holy: ${#modules[@]} app(s): ${modules[*]:-none}"
